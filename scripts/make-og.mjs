// Builds the link preview card (og.png, 1200x630) and the home screen icon (apple-touch-icon.png, 180x180).
// Run from the repo root: node scripts/make-og.mjs
//
// The card draws one real day of ERCOT day-ahead prices at Houston Hub from data/ercot-dam-houston.json, with the
// site's own battery schedule from data/day-ercot.json shaded on it (charge 10 AM to 2 PM, discharge 7 to 9 PM,
// Central). That schedule is the site's example, not Base Power's dispatch. Rerun after either file changes.
//
// No dependencies: it writes the card as HTML (scripts/og/card.html, kept so the source of the PNG can be read) and
// asks a local Chromium browser (Edge or Chrome, or the path in $OG_BROWSER) to screenshot it.
import { readFileSync, writeFileSync, mkdirSync, existsSync, statSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { tmpdir } from 'node:os';

const ROOT = resolve(import.meta.dirname, '..');
const prices = JSON.parse(readFileSync(join(ROOT, 'data/ercot-dam-houston.json'), 'utf8'));
const schedule = JSON.parse(readFileSync(join(ROOT, 'data/day-ercot.json'), 'utf8')).schedule;

const hours = prices.hours.slice().sort((a, b) => a.hour_ending - b.hour_ending).map((h) => h.usd_mwh);
if (hours.length !== 24 || hours.some((v) => typeof v !== 'number')) throw new Error('expected 24 hourly prices in data/ercot-dam-houston.json');
const [c0, c1] = schedule.charge, [r0, r1] = schedule.discharge; // hour of day the window starts and ends, Central

const date = new Date(prices.delivery_date + 'T12:00:00Z');
const dateLabel = date.toLocaleDateString('en-US', { month: 'short', day: 'numeric', year: 'numeric', timeZone: 'UTC' });

// Base Power's public colors, as the site's --bpc-* tokens name them (site.css).
const C = { bg: '#1e4d2b', line: '#ffffff', charge: '#b2dd79', run: '#ed6c30', small: '#d8d7d5' };

// Chart: lower part of the card, inside 64px margins.
const W = 1200, H = 630, M = 64, top = 318, bottom = 520, left = M, right = W - M;
const x = (h) => left + (h / 24) * (right - left);
const lo = Math.min(...hours), hi = Math.max(...hours), pad = (hi - lo) * 0.12;
const y = (v) => bottom - ((v - (lo - pad)) / (hi + pad - (lo - pad))) * (bottom - top);
let path = `M${x(0).toFixed(1)} ${y(hours[0]).toFixed(1)}`;
hours.forEach((v, h) => { path += `H${x(h + 1).toFixed(1)}`; if (h < 23) path += `V${y(hours[h + 1]).toFixed(1)}`; }); // one flat step per hour
const band = (a, b, fill) => `<rect x="${x(a).toFixed(1)}" y="${top - 8}" width="${(x(b) - x(a)).toFixed(1)}" height="${bottom - top + 8}" fill="${fill}"/>`;
const label = (a, b, text, fill) => `<text x="${((x(a) + x(b)) / 2).toFixed(1)}" y="${top - 22}" text-anchor="middle" fill="${fill}" font-size="26" font-weight="500">${text}</text>`;
const ticks = [[0, '12a'], [6, '6a'], [12, '12p'], [18, '6p'], [24, '12a']]
  .map(([h, t], i, a) => `<text x="${x(h).toFixed(1)}" y="${bottom + 34}" text-anchor="${i === 0 ? 'start' : i === a.length - 1 ? 'end' : 'middle'}" fill="${C.small}" font-size="20">${t}</text>`).join('');

const font = (w) => `@font-face { font-family: "Instrument Sans"; src: url("${pathToFileURL(join(ROOT, `fonts/instrument-sans-latin-${w}-normal.woff2`))}") format("woff2"); font-weight: ${w}; }`;
const card = `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><title>megawatt.fun link preview</title>
<!-- Generated by scripts/make-og.mjs from data/ercot-dam-houston.json and data/day-ercot.json. Do not edit by hand. -->
<style>
${font(400)} ${font(500)} ${font(600)}
html, body { margin: 0; width: ${W}px; height: ${H}px; overflow: hidden; background: ${C.bg}; }
body { position: relative; font-family: "Instrument Sans", sans-serif; color: #fff; }
.site { position: absolute; left: ${M}px; top: 52px; font-size: 30px; font-weight: 500; color: ${C.small}; }
h1 { position: absolute; left: ${M}px; top: 112px; margin: 0; font-size: 72px; line-height: 1; font-weight: 600; letter-spacing: -0.5px; }
svg { position: absolute; left: 0; top: 0; font-family: "Instrument Sans", sans-serif; }
.foot { position: absolute; left: ${M}px; right: ${M}px; bottom: 34px; font-size: 20px; color: ${C.small}; white-space: nowrap; }
</style></head>
<body>
<div class="site">megawatt.fun</div>
<h1>One battery, one day</h1>
<svg width="${W}" height="${H}" viewBox="0 0 ${W} ${H}" aria-hidden="true">
${band(c0, c1, C.charge)}${band(r0, r1, C.run)}
<line x1="${left}" x2="${right}" y1="${bottom + 8}" y2="${bottom + 8}" stroke="${C.small}" stroke-opacity=".35" stroke-width="1"/>
<path d="${path}" fill="none" stroke="${C.bg}" stroke-width="10" stroke-linejoin="round" stroke-linecap="round"/><!-- a dark edge, so the line reads over the light green band -->
<path d="${path}" fill="none" stroke="${C.line}" stroke-width="4" stroke-linejoin="round" stroke-linecap="round"/>
${label(c0, c1, 'charges', C.charge)}${label(r0, r1, 'runs the home', C.run)}
${ticks}
</svg>
<div class="foot">ERCOT day-ahead prices, Houston Hub, ${dateLabel} · by Adam Pang · Not affiliated with Base Power</div>
</body></html>
`;

const icon = `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><title>megawatt.fun icon</title>
<!-- Generated by scripts/make-og.mjs. A plain battery mark, not Base Power's logo. -->
<style>html, body { margin: 0; width: 180px; height: 180px; overflow: hidden; background: ${C.bg}; }</style></head>
<body><svg width="180" height="180" viewBox="0 0 180 180" aria-hidden="true">
<rect x="56" y="38" width="68" height="112" rx="10" fill="none" stroke="${C.charge}" stroke-width="10"/>
<rect x="76" y="24" width="28" height="14" rx="3" fill="${C.charge}"/>
<rect x="70" y="92" width="40" height="44" rx="3" fill="${C.charge}"/>
</svg></body></html>
`;

const outDir = join(ROOT, 'scripts/og');
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'card.html'), card);
writeFileSync(join(outDir, 'icon.html'), icon);

const candidates = [process.env.OG_BROWSER,
  'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', 'C:/Program Files/Microsoft/Edge/Application/msedge.exe',
  'C:/Program Files/Google/Chrome/Application/chrome.exe', '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
  '/usr/bin/google-chrome', '/usr/bin/chromium', '/usr/bin/chromium-browser'].filter(Boolean);
const browser = candidates.find((p) => existsSync(p));
if (!browser) throw new Error('No Chromium browser found. Set OG_BROWSER to its path.');

function shoot(html, out, w, h) {
  execFileSync(browser, ['--headless=new', '--disable-gpu', '--hide-scrollbars', '--force-device-scale-factor=1',
    `--user-data-dir=${join(tmpdir(), 'megawatt-og-profile')}`, '--virtual-time-budget=3000',
    `--window-size=${w},${h}`, `--screenshot=${out}`, pathToFileURL(html).href], { stdio: 'ignore' });
  console.log(out.replace(ROOT, '.'), statSync(out).size, 'bytes');
}
shoot(join(outDir, 'card.html'), join(ROOT, 'og.png'), W, H);
shoot(join(outDir, 'icon.html'), join(ROOT, 'apple-touch-icon.png'), 180, 180);
